import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const root = resolve(scriptDir, "..");
const deploymentsDir = join(root, "deployments");
const output = join(root, "bindings", "liquidity-pool", "src", "deployments.ts");

const deployments = Object.fromEntries(
  readdirSync(deploymentsDir)
    .filter((file) => file.endsWith(".json"))
    .sort()
    .map((file) => {
      const deployment = JSON.parse(readFileSync(join(deploymentsDir, file), "utf8"));
      const network = deployment.network ?? basename(file, ".json");
      return [network, deployment];
    }),
);

const networks = Object.keys(deployments);
const generated = `// Generated by scripts/generate-sdk-deployments.mjs. Do not edit by hand.\n` +
  `export interface RouterDeployment {\n` +
  `  address: string;\n` +
  `  owner: string;\n` +
  `  pool_wasm_hash: string;\n` +
  `  default_protocol_fee: number;\n` +
  `  default_protocol_beneficiary: string;\n` +
  `  permissionless_creation: boolean;\n` +
  `}\n\n` +
  `export interface TokenRepresentation {\n` +
  `  address: string;\n` +
  `  kind: string;\n` +
  `  initial_balance?: string;\n` +
  `  [key: string]: unknown;\n` +
  `}\n\n` +
  `export interface TokenDeployment {\n` +
  `  id: string;\n` +
  `  category: "usd" | "eur" | "crypto";\n` +
  `  name: string;\n` +
  `  symbol: string;\n` +
  `  decimals: number;\n` +
  `  soroban: TokenRepresentation;\n` +
  `  sac: TokenRepresentation;\n` +
  `}\n\n` +
  `export interface PoolDeploymentDefaults {\n` +
  `  swap_fee: number;\n` +
  `}\n\n` +
  `export interface NetworkDeployment {\n` +
  `  network: string;\n` +
  `  deployed_at?: string;\n` +
  `  source_identity?: string;\n` +
  `  deployer?: string;\n` +
  `  contracts: {\n` +
  `    router?: RouterDeployment;\n` +
  `    tokens?: TokenDeployment[];\n` +
  `    [key: string]: unknown;\n` +
  `  };\n` +
  `  pool_defaults?: PoolDeploymentDefaults;\n` +
  `  [key: string]: unknown;\n` +
  `}\n\n` +
  `export const deploymentNetworks = ${JSON.stringify(networks)} as const;\n` +
  `export type DeploymentNetwork = (typeof deploymentNetworks)[number];\n` +
  `export const deployments: Record<DeploymentNetwork, NetworkDeployment> = ${JSON.stringify(deployments, null, 2)};\n` +
  `export type Deployment = NetworkDeployment;\n`;

writeFileSync(output, generated);
console.log(`Generated ${output}`);
